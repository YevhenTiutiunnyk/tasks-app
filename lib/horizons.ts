import { startOfMonth, startOfWeek } from './dates';

/**
 * Горизонт задачи: насколько крупному куску времени она принадлежит.
 *
 * `day` — как было всегда: конкретный день, с временем или без.
 * `week` и `month` — дела без дня: «починить кран на этой неделе».
 */
export type Horizon = 'day' | 'week' | 'month';

/**
 * Дата, под которой задача горизонта лежит в базе.
 *
 * У задачи любого горизонта колонка `date` заполнена — она работает якорем
 * периода. Для недели это понедельник, для месяца — первое число. Благодаря
 * этому `date` осталась обязательной, и ни одна существующая гарантия схемы
 * не ослаблена.
 *
 * Приведение делает наш код, а не модель. Модель отдаёт горизонт и любую дату
 * внутри периода; вычислять понедельники ей нельзя — она в этом ошибается,
 * а здесь это две строки проверенного и бесплатного кода.
 */
export function anchorFor(horizon: Horizon, iso: string): string {
  if (horizon === 'week') return startOfWeek(iso);
  if (horizon === 'month') return startOfMonth(iso);
  return iso;
}
