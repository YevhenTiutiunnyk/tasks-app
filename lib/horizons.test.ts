import { describe, expect, it } from 'vitest';
import { anchorFor } from './horizons';

describe('anchorFor', () => {
  it('дневной горизонт оставляет дату как есть', () => {
    expect(anchorFor('day', '2026-09-17')).toBe('2026-09-17');
  });

  it('недельный приводит к понедельнику', () => {
    // 2026-09-17 — четверг.
    expect(anchorFor('week', '2026-09-17')).toBe('2026-09-14');
  });

  it('недельный на самом понедельнике не двигается', () => {
    expect(anchorFor('week', '2026-09-14')).toBe('2026-09-14');
  });

  it('недельный в воскресенье остаётся в своей неделе', () => {
    // Воскресенье — последний день недели, а не первый день следующей.
    // Наивная реализация через «ближайший понедельник вперёд» уводила бы
    // воскресную задачу в следующую неделю, и это заметили бы только через
    // неделю пользования.
    expect(anchorFor('week', '2026-09-20')).toBe('2026-09-14');
  });

  it('месячный приводит к первому числу', () => {
    expect(anchorFor('month', '2026-09-17')).toBe('2026-09-01');
  });

  it('недельный на стыке месяцев уходит в предыдущий месяц, если там понедельник', () => {
    // 2026-10-01 — четверг, понедельник его недели лежит в сентябре.
    // Это правильно: неделя важнее месяца, когда горизонт недельный.
    expect(anchorFor('week', '2026-10-01')).toBe('2026-09-28');
  });
});
