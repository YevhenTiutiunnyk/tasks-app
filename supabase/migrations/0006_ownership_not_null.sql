-- Колонки владельца становятся обязательными. Догоняющая миграция.
--
-- ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА 0004
--
-- Ровно это делает фаза 3 миграции 0004_ownership.sql — но она там
-- закомментирована. Её применяли к боевой базе вручную, раскомментировав
-- на время и вернув комментарии обратно. Правило проекта — старые файлы
-- миграций не переписывать, поэтому раскомментировать 0004 задним числом
-- нельзя: у того, кто уже прогонял миграции, файл изменился бы под ногами.
-- Новый файл — единственный законный способ довести дело до конца.
--
-- ЧТО ЭТО ЧИНИТ
--
-- scripts/test-db.sh собирает схему тестового контейнера настоящими файлами
-- миграций — и потому фазу 3 не выполняет никогда. Итог, проверенный
-- 2026-08-31: в боевой базе user_id обязателен, в тестовом контейнере нет.
--
-- Расхождение этого вида опаснее обычного дефекта. Вставка, забывшая
-- владельца, в тестах проходит зелёной, а в бою падает — то есть тесты
-- начинают врать в самую опасную сторону. Ради недопущения ровно этого
-- test-db.sh и собирает схему из миграций, а не из ручной копии; дыра была
-- не в замысле, а в том, что часть миграции жила в комментариях.
--
-- ДЛЯ БОЕВОЙ БАЗЫ ЭТО ПУСТАЯ ОПЕРАЦИЯ
--
-- Там колонки уже not null с 2026-08-21. Повторный set not null на колонке,
-- которая уже not null, Postgres принимает молча и таблицу не перечитывает.
-- Применять безопасно и нужно — иначе следующий, кто соберёт базу с нуля
-- по файлам, снова получит расхождение.
--
-- ПРЕДОХРАНИТЕЛЬ ВСТРОЕН В САМУ ОПЕРАЦИЮ
--
-- set not null проверяет таблицу и отказывается, если хоть в одной строке
-- user_id пуст. Отдельная проверка была бы дублем: падение и так будет
-- громким и назовёт колонку. Если оно случится на боевой базе — значит там
-- есть строки без владельца, и это отдельная беда, которую надо разбирать
-- до, а не обходить.
--
-- Всё в одной транзакции: либо обязательными становятся все четыре колонки,
-- либо ни одна.

begin;

alter table tasks              alter column user_id set not null;
alter table recurrences        alter column user_id set not null;
alter table command_log        alter column user_id set not null;
alter table push_subscriptions alter column user_id set not null;

commit;
