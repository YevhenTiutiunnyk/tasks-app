-- Снимок недели: что было запланировано и что из этого вышло.
--
-- ЗАЧЕМ ИМЕННО СНИМОК
--
-- Отчёт отвечает на вопрос «сверить намерение с реальностью». Намерение —
-- это состояние недели на её начало, и проще всего его именно записать,
-- а не восстанавливать задним числом. Журнал событий дал бы больше, но
-- писать его пришлось бы в пяти местах, где меняется задача, и каждое
-- можно забыть.
--
-- ПОЧЕМУ jsonb, А НЕ СТРОКА НА ЗАДАЧУ
--
-- Данных мало: неделя задач одного человека. Сравнение делается
-- в TypeScript чистой функцией, которую можно проверить без базы.
-- В проекте так уже устроены command_log.snapshot и
-- user_settings.categories.
--
-- В planned лежит массив {id, title}. Название хранится рядом
-- с идентификатором намеренно: задачу могут удалить, и тогда снимок
-- останется единственным местом, где известно, как она называлась.
--
-- В report лежит готовый отчёт. Он считается один раз, при отправке,
-- и потом только читается: пересчитай его при открытии экрана — и цифры
-- разъедутся с теми, что человек уже увидел в уведомлении.
--
-- ЗАЧЕМ reported_at
--
-- Планировщик стучится раз в минуту, а отчёт должен уйти ровно один раз.
-- Отправили — проставили время; следующий запуск видит его и молчит.
-- Без этого поля человек получал бы пуш каждую минуту весь понедельник.
--
-- Владелец обязателен сразу, а не догоняющей миграцией: урок 0004 и 0006.

begin;

create table week_snapshots (
  user_id     text        not null references "user" ("id") on delete restrict,
  week_start  date        not null,
  planned     jsonb       not null,
  report      jsonb,
  reported_at timestamptz,
  created_at  timestamptz not null default now(),
  primary key (user_id, week_start)
);

commit;
