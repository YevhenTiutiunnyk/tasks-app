-- Горизонт задачи: день, неделя или месяц.
--
-- ЗАЧЕМ
--
-- Половина дел не имеет дня. «Починить кран» надо на этой неделе, «сдать
-- отчёт» — в этом месяце. До сих пор положить такое дело было некуда:
-- date обязательна, и приходилось назначать час, в который никто ничего
-- делать не собирается.
--
-- ПОЧЕМУ date ОСТАЁТСЯ ОБЯЗАТЕЛЬНОЙ
--
-- Она работает якорем периода: у недельной задачи это понедельник её
-- недели, у месячной — первое число месяца. Иначе пришлось бы делать
-- drop not null и заводить вторую колонку под период, то есть ослаблять
-- существующую гарантию ради нового поля. Миграция 0006 ровно эти
-- гарантии ужесточала, и разворачивать движение назад не хочется.
--
-- Плата за решение названа вслух: date = 2026-09-01 у месячной задачи
-- означает «сентябрь», а не «первое сентября». Смысл держится на horizon
-- и на комментариях у запросов.
--
-- ПОЧЕМУ У КОЛОНКИ ЕСТЬ default, ХОТЯ ЗНАЧЕНИЕ ВСЕГДА СТАВИТ КОД
--
-- Ради окна между миграцией и выкладкой. Миграцию применяют к боевой базе
-- ДО деплоя, то есть какое-то время с новой схемой работает старый код —
-- а он не знает про horizon и вставляет задачи без него. Без умолчания
-- каждая такая вставка падала бы на not null, и приложение стояло бы
-- сломанным всё это окно.
--
-- Побочная выгода: ни один существующий insert в коде и в тестах не надо
-- переписывать ради новой колонки.
--
-- Три шага, а не один: тот же порядок, каким шли 0004 и 0006 — добавить,
-- заполнить, ужесточить. На боевой таблице заполняющий update совпадёт
-- с нулём строк: константный default из add column Postgres применяет
-- к существующим строкам сразу, без перезаписи таблицы. Шаг оставлен
-- сознательно — он ничего не стоит и остаётся верным для базы, собранной
-- иначе, а set not null проверит результат в любом случае.
--
-- Проверки значений на уровне базы нет намеренно: допустимые горизонты
-- перечислены типом в lib/types.ts и проверяются схемой разбора, а
-- check-ограничение пришлось бы менять новой миграцией при появлении
-- четвёртого горизонта. Ограничение на регистр в allowed_emails стоит
-- потому, что туда пишут руками из SQL-редактора; сюда пишет только код.

begin;

alter table tasks add column horizon text default 'day';
update tasks set horizon = 'day' where horizon is null;
alter table tasks alter column horizon set not null;

commit;
