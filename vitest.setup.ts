// lib/db.ts создаёт пул подключений на уровне модуля — `postgres(process.env
// .DATABASE_URL!)` выполняется в момент первого импорта, а не при вызове
// функции. Значит, подменять адрес нужно до того, как хоть один тестовый
// файл успеет импортировать lib/db.ts, — иначе пул уже будет собран на
// боевой строке, и подмена ничего не изменит. vitest гарантированно
// выполняет setupFiles раньше импортов самого тестового файла, поэтому
// подмена стоит здесь, а не в отдельном тестовом файле.
//
// Смысл — не «удобство», а то, что ни один тест не должен иметь возможности
// достучаться до боевой базы вообще, даже если кто-то забудет флаг
// с переменной окружения. Мутационное тестирование по боевой базе уже
// однажды стёрло журнал отмены целиком (см. task-3b-brief.md) — эта проверка
// физически исключает повтор, а не полагается на то, что её не забудут.

const testUrl = process.env.TEST_DATABASE_URL;
const prodUrl = process.env.DATABASE_URL;

// Без DATABASE_URL в окружении вообще (обычный `npx vitest run`, без
// --env-file) база никому не нужна: файлы, которым она нужна, сами себя
// пропускают через `describe.skip` (см. lib/db.test.ts, lib/apply.test.ts,
// lib/ownership.test.ts). Требовать здесь TEST_DATABASE_URL в этом случае
// значило бы ломать именно этот документированный в README режим — прогон
// одних тестов чистых функций без контейнера и без .env.local вовсе.
//
// Опасный случай — ровно противоположный: DATABASE_URL присутствует
// (обычно из --env-file=.env.local, где лежит боевая строка), а
// TEST_DATABASE_URL потерялась или не задана. Тогда ниже некуда
// подставлять, и без явного отказа тесты тихо пошли бы в боевую базу.
if (prodUrl !== undefined) {
  if (!testUrl) {
    throw new Error(
      'DATABASE_URL задана, а TEST_DATABASE_URL — нет. Тесты, обращающиеся ' +
        'к базе, нарочно отказываются стартовать в таком виде — иначе они ' +
        'рискуют молча уйти в боевую. Поднимите тестовый контейнер ' +
        '(scripts/test-db.sh) и пропишите TEST_DATABASE_URL в .env.local ' +
        '(см. README).',
    );
  }

  const test = describeConnection(testUrl, 'TEST_DATABASE_URL');
  const prod = describeConnection(prodUrl, 'DATABASE_URL');

  // Сравнение по смыслу, а не по строке. Посимвольное равенство пропускало
  // одну и ту же базу, записанную иначе: postgres:// против postgresql://,
  // добавленный ?sslmode=require, другой пользователь в строке, другой порт.
  // Каждый такой случай — тесты в боевой базе при формально «разных»
  // переменных, а это единственный автоматический барьер, и набор тестов
  // уже дважды навредил живым данным.
  //
  // Порт в решении не участвует намеренно, хотя и разбирается ниже (он идёт
  // в текст ошибки, чтобы тот не врал). У Supabase 5432 и 6543 — прямое
  // соединение и транзакционный пулер к ОДНОЙ И ТОЙ ЖЕ базе: считай порт
  // отличием — и подмена 6543 на 5432 прошла бы барьер насквозь. Обратная
  // цена — отказ для настоящего тестового Postgres на том же хосте и с тем
  // же именем базы, что у боевого. Это дёшево лечится (имя базы у тестового
  // контейнера своё — tasks_test) и всяко лучше обратной ошибки.
  if (test.host === prod.host && test.database === prod.database) {
    throw new Error(
      `TEST_DATABASE_URL (${test.shown}) и DATABASE_URL (${prod.shown}) ведут ` +
        'в одну и ту же базу — совпали хост и имя базы. Это ровно то, от чего ' +
        'защищается эта проверка: с такими значениями тесты писали бы ' +
        'в боевую базу. Проверьте .env.local — переменные обязаны указывать ' +
        'на разные базы. Порт здесь не спасает: 5432 и 6543 у Supabase — два ' +
        'входа в одну базу.',
    );
  }

  process.env.DATABASE_URL = testUrl;
}

/**
 * Строка подключения, разобранная до того, что определяет саму базу.
 *
 * Объявлена после использования намеренно: подъём объявлений функций даёт
 * читателю проверку первой, а служебный разбор — вторым.
 */
function describeConnection(
  raw: string,
  variable: string,
): { host: string; database: string; shown: string } {
  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    // Неразобранная строка — не повод пропустить: доказать, что она ведёт
    // не в боевую базу, тут нечем, а барьер существует ровно для случаев,
    // когда что-то пошло не так.
    throw new Error(
      `${variable} не разбирается как адрес подключения. Ожидается вид ` +
        'postgresql://пользователь:пароль@хост:порт/база — без этого нельзя ' +
        'убедиться, что тесты не пойдут в боевую базу.',
    );
  }
  // Хост в DNS регистронезависим, а сравнение строк — нет.
  const host = url.hostname.toLowerCase();
  // Порт может быть не указан явно: у Postgres умолчание — 5432.
  const port = url.port || '5432';
  // Имя базы — путь без ведущего слеша; параметры (?sslmode=…) сюда не
  // попадают, чем и снимается целый класс мнимых различий.
  const database = decodeURIComponent(url.pathname.replace(/^\//, ''));
  return { host, database, shown: `${host}:${port}/${database}` };
}
