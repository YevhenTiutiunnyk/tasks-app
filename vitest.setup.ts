// lib/db.ts создаёт пул подключений на уровне модуля — `postgres(process.env
// .DATABASE_URL!)` выполняется в момент первого импорта, а не при вызове
// функции. Значит, подменять адрес нужно до того, как хоть один тестовый
// файл успеет импортировать lib/db.ts, — иначе пул уже будет собран на
// боевой строке, и подмена ничего не изменит. vitest гарантированно
// выполняет setupFiles раньше импортов самого тестового файла, поэтому
// подмена стоит здесь, а не в отдельном тестовом файле.
//
// Смысл — не «удобство», а то, что ни один тест не должен иметь возможности
// достучаться до боевой базы вообще, даже если кто-то забудет флаг
// с переменной окружения. Мутационное тестирование по боевой базе уже
// однажды стёрло журнал отмены целиком (см. task-3b-brief.md) — эта проверка
// физически исключает повтор, а не полагается на то, что её не забудут.

const testUrl = process.env.TEST_DATABASE_URL;
const prodUrl = process.env.DATABASE_URL;

// Без DATABASE_URL в окружении вообще (обычный `npx vitest run`, без
// --env-file) база никому не нужна: файлы, которым она нужна, сами себя
// пропускают через `describe.skip` (см. lib/db.test.ts, lib/apply.test.ts,
// lib/ownership.test.ts). Требовать здесь TEST_DATABASE_URL в этом случае
// значило бы ломать именно этот документированный в README режим — прогон
// одних тестов чистых функций без контейнера и без .env.local вовсе.
//
// Опасный случай — ровно противоположный: DATABASE_URL присутствует
// (обычно из --env-file=.env.local, где лежит боевая строка), а
// TEST_DATABASE_URL потерялась или не задана. Тогда ниже некуда
// подставлять, и без явного отказа тесты тихо пошли бы в боевую базу.
if (prodUrl !== undefined) {
  if (!testUrl) {
    throw new Error(
      'DATABASE_URL задана, а TEST_DATABASE_URL — нет. Тесты, обращающиеся ' +
        'к базе, нарочно отказываются стартовать в таком виде — иначе они ' +
        'рискуют молча уйти в боевую. Поднимите тестовый контейнер ' +
        '(scripts/test-db.sh) и пропишите TEST_DATABASE_URL в .env.local ' +
        '(см. README).',
    );
  }

  if (testUrl === prodUrl) {
    throw new Error(
      'TEST_DATABASE_URL совпадает с DATABASE_URL. Это ровно то, от чего ' +
        'защищается эта проверка: с такими значениями тесты писали бы ' +
        'в боевую базу. Проверьте .env.local — переменные обязаны указывать ' +
        'на разные базы.',
    );
  }

  process.env.DATABASE_URL = testUrl;
}
