/**
 * Стрелка для кнопок навигации: переключение недель, возврат из настроек.
 *
 * Рисуется, а не набирается символом «←»: стрелочные глифы Geist тоньше
 * соседних подписей и на бумажном фоне теряются, а толщину глифа не задать
 * ничем. У линии же она своя — strokeWidth, и стрелка весит ровно столько,
 * сколько нужно, в обеих темах.
 *
 * Лежит в общем месте, потому что мест стало два: на главном экране и в
 * настройках. Две копии одного пути разъехались бы при первой же правке.
 */
export function Chevron({ direction }: { direction: 'left' | 'right' }) {
  return (
    <svg
      viewBox="0 0 24 24"
      className="h-4 w-4"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      <path d={direction === 'left' ? 'M15 5 8 12l7 7' : 'M9 5l7 7-7 7'} />
    </svg>
  );
}
