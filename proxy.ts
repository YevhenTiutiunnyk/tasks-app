import { NextResponse, type NextRequest } from 'next/server';
import { auth } from '@/lib/auth';
import { isEmailAllowed, revokeSessions } from '@/lib/allowed-emails';

// Начиная с Next 16 это соглашение зовётся `proxy`: файл называется proxy.ts,
// функция — proxy. Прежнее имя, middleware, ещё работает, но собирается
// с предупреждением о том, что соглашение устарело.
//
// Здесь стоит НАСТОЯЩАЯ проверка сессии, с обращением к базе, а не проверка
// наличия куки. Так решено сознательно: getSessionCookie у Better Auth куку
// не проверяет, и опора на него означала бы, что войти может любой, кто сам
// себе эту куку выставит.
//
// Пускать или не пускать решается только здесь — это общий вход, и роуты
// эту развилку не повторяют. Но с тех пор, как у данных появился владелец,
// роуты спрашивают сессию ещё раз, через requireUser: им нужен не ответ
// «пускать ли», а чьи данные читать. Отсутствие сессии там — не вторая линия
// обороны, а отказ угадывать: до роута без сессии дело дойти не должно,
// и если дошло, честнее ответить 401, чем показать чужое расписание.
//
// Это законно потому, что в Next 16 proxy по умолчанию работает на
// Node-рантайме (опция runtime здесь запрещена и бросает ошибку).
export async function proxy(request: NextRequest) {
  let result;
  try {
    // returnHeaders: true — не украшение вызова, а единственный способ забрать
    // у Better Auth то, что он приготовил для браузера. Форму подсказывают
    // типы getSession (node_modules/better-auth/dist/types/api.d.mts): при
    // returnHeaders ответ приходит как { headers, response }, где response —
    // сама сессия или null.
    result = await auth.api.getSession({ headers: request.headers, returnHeaders: true });
  } catch (error) {
    // Лог без куки и заголовков: в них лежит содержимое сессии, а причина
    // отказа — обрыв связи с базой — в них не написана и без утечки видна.
    console.error('proxy: не удалось проверить сессию', error);
    // Не редирект на /login: моргнувшая база выбросила бы на вход и уже
    // вошедшего пользователя, а сам вход без базы тоже не сработает — это
    // была бы дорога в никуда. 503 честно говорит, что дело не в сессии, и
    // одинаков для страниц и для api — здесь, в отличие от развилки ниже,
    // разбирать ответ на стороне клиента не нужно: это не отказ входа,
    // а сообщение "попробуй позже" в любом виде.
    return NextResponse.json({ error: 'Сервис временно недоступен' }, { status: 503 });
  }
  if (result.response) {
    // Белый список проверяется здесь, на КАЖДОМ запросе, а не только при
    // создании сессии. Без этого убранный из allowed_emails адрес работал бы
    // до 30 дней — столько живёт сессия, а скольжение продлевает срок при
    // каждом визите, то есть у активного человека доступ не кончился бы
    // никогда.
    //
    // Адрес берётся из уже полученной сессии: getSession возвращает
    // { session, user }, и лишнего запроса за ним не нужно.
    let allowed: boolean;
    try {
      allowed = await isEmailAllowed(result.response.user.email);
    } catch (error) {
      // Тот же ответ, что и на обрыве getSession выше, и по той же причине.
      // Проверка допуска, которая при моргнувшей базе молча пропускает, —
      // не проверка. Выбрасывать на вход тоже нельзя: вход без базы не
      // сработает, получилась бы дорога в никуда.
      console.error('proxy: не удалось проверить белый список', error);
      return NextResponse.json({ error: 'Сервис временно недоступен' }, { status: 503 });
    }

    if (!allowed) {
      const userId = result.response.user.id;
      // Снимаем сессии со всех устройств: отзыв по адресу, а не по браузеру.
      // Без этого человек бился бы в закрытую дверь до естественного
      // истечения сессии, тратя по два запроса к базе на каждую попытку.
      try {
        const revoked = await revokeSessions(userId);
        // В лог идёт userId, а не адрес: идентификатора хватает, чтобы найти
        // строку, а раскладывать почту людей по логам Vercel незачем.
        console.error(`proxy: доступ отозван, userId=${userId}, снято сессий: ${revoked}`);
      } catch (error) {
        // Отказ решён строкой выше — адреса нет в белом списке, — и от
        // зачистки сессий это решение не зависит: она лишь сопутствующий
        // эффект, а не условие отказа. Обрыв базы здесь не должен ни
        // впустить человека (адрес всё равно не в списке), ни уронить
        // прокси необработанной 500-кой вместо честного 307/401 — тогда
        // потерялась бы и эта строка лога, единственный след события.
        console.error('proxy: не удалось снять сессии при отзыве', error);
      }
      // Заголовки НЕ переносим — вот это важно. result.headers могут нести
      // свежую куку сессии, которую Better Auth приготовил при скольжении
      // срока. Отдать её человеку, у которого мы только что удалили сессию
      // (или пытались это сделать), значило бы вручить ключ от снятого
      // замка. Куку уберёт следующий же запрос: если сессии больше нет,
      // сработает ветка «сессии нет»; если зачистка не удалась — тот же
      // отказ просто повторится на следующей попытке.
      return denyResponse(request, new Headers());
    }

    const response = NextResponse.next();
    // Скольжение срока живёт здесь. По истечении updateAge getSession сам
    // продлевает строку сессии в базе и кладёт свежую куку в заголовки своего
    // контекста, но NextResponse.next() их не наследует — без переноса срок
    // в браузере навсегда остался бы тем, что выдан при входе, и сессия
    // умирала бы через 30 дней после входа, а не после последнего визита.
    // Заметить это можно было бы только через месяц и только по внезапному
    // возврату на страницу входа.
    return withSetCookies(response, result.headers);
  }
  // Сессии нет. Кука в запросе могла быть протухшей — тогда getSession уже
  // положил в result.headers команду на её удаление, и её надо перенести.
  return denyResponse(request, result.headers);
}

// Общее место для переноса Set-Cookie из ответа Better Auth в ответ прокси.
// Вызывающих двое: сама proxy() — для ветки «сессия есть», и denyResponse —
// для api и страниц разом. А форм вызова четыре: настоящие заголовки в
// каждой из трёх (сессия есть, 401, 307) и намеренно пустые в четвёртой —
// при отзыве, когда denyResponse зовут с new Headers() (см. её комментарий
// ниже). Раскопируй цикл по каждой из веток вместо общего места — и эти
// четыре формы разъедутся при первой же правке.
//
// append и весь список: кук бывает несколько (токен сессии и её кэш), а set
// оставил бы одну.
function withSetCookies<T extends NextResponse>(response: T, headers: Headers): T {
  for (const cookie of headers.getSetCookie()) {
    response.headers.append('set-cookie', cookie);
  }
  return response;
}

/**
 * Ответ «доступа нет»: страницам — на вход, api — 401.
 *
 * Вынесено потому, что таких мест стало два: сессии действительно нет, либо
 * она есть, но адрес убрали из белого списка. Для клиента это одно и то же
 * состояние, и отвечать надо одинаково — две копии разъехались бы при первой
 * же правке, ровно как это случилось бы с withSetCookies.
 *
 * headers у двух вызывающих разные не просто так. Когда сессии действительно
 * нет, сюда приходит настоящий result.headers: кука в запросе могла быть
 * протухшей, тогда getSession уже положил в него команду на её удаление,
 * и перенести её можно без опаски — открыть это не открывает, команда одна,
 * на удаление, продлевать здесь нечего. А когда сессия есть, но адрес
 * отозван, result.headers мог бы нести свежую куку скольжения — вот её
 * как раз открывать нельзя, это ключ от только что снятого замка, — поэтому
 * туда передают new Headers(), пустышку, а не то, что вернул Better Auth.
 */
function denyResponse(request: NextRequest, headers: Headers): NextResponse {
  if (request.nextUrl.pathname.startsWith('/api/')) {
    // Кука в запросе могла быть протухшей — тогда getSession сам зовёт
    // deleteSessionCookie и кладёт в headers команду на её удаление
    // (node_modules/better-auth/dist/api/routes/session.mjs, ветка истёкшей
    // сессии). Не перенеси мы её — браузер держал бы мёртвую куку до её
    // собственного Max-Age (до 30 дней), и каждый запрос заново бил бы
    // в базу впустую.
    return withSetCookies(
      NextResponse.json({ error: 'Не авторизован' }, { status: 401 }),
      headers,
    );
  }
  // Та же чистка и по той же причине — для страниц.
  return withSetCookies(NextResponse.redirect(new URL('/login', request.url)), headers);
}

// Всё, кроме статики, страницы входа и роутов Better Auth.
//
// Манифест, иконки и service worker браузер запрашивает без кук — у
// <link rel="manifest"> нет crossorigin="use-credentials", и Next его не
// добавляет. Без исключений они получали бы редирект на /login, iOS не
// разобрала бы манифест, и приложение осталось бы закладкой Safari. Молча:
// ни ошибки, ни записи в логах. Наружу при этом открыты только название,
// цвета и картинка — в базу эти маршруты не ходят.
//
// Сюда же добавлен api/notify: его дёргает планировщик из Supabase, у которого
// никакой сессии нет и быть не может. Роут защищён своим секретом в заголовке.
//
// Каждое исключение заякорено, иначе оно открывает наружу всё, что просто
// начинается так же. Якоря здесь трёх видов, и вид определяется тем, в каких
// формах путь приходит:
//
// `$` — для того, что браузер просит ровно одним путём: манифест, sw.js,
// иконки, api/notify. Без якоря `icon` открыл бы и /iconxyz, и /icons/secret.
//
// слеш — для api/auth/: Better Auth это catch-all с десятком путей, и `$` тут
// всё сломал бы. Роль якоря играет слеш, он не пускает /api/authxyz.
//
// `(?:$|\.)` — для login и favicon.ico, которые Next просит ещё и в
// транспортных формах (/login.rsc при префетче страницы входа). `$` здесь
// применить НЕЛЬЗЯ: группа транспортных суффиксов стоит снаружи lookahead,
// поэтому `$` внутри означает конец всего пути, и `login$` перестал бы
// исключать /login.rsc — прокси отправил бы префетч входа в редирект и сломал
// бы клиентскую навигацию. Точка в favicon\.ico экранирована: без этого она
// значила «любой символ» и открывала /faviconXico.
//
// Все три вида проверяются в proxy.test.ts — на регулярке, собранной в той же
// форме, в какую матчер компилирует Next.
export const config = {
  matcher: [
    '/((?!login(?:$|\\.)|api/auth/|api/notify$|_next/static|_next/image|favicon\\.ico(?:$|\\.)|manifest\\.webmanifest$|sw\\.js$|icon$|apple-icon$).*)',
  ],
};
